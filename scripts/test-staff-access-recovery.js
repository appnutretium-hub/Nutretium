'use strict';
const assert=require('assert');
const crypto=require('crypto');
process.env.NUTRETIUM_TEST_MEMORY_BLOBS='true';
process.env.JWT_SECRET=crypto.randomBytes(48).toString('hex');
process.env.ADMIN_EMAILS='recovery-owner@nutretium.test';
process.env.REQUIRE_STAFF_MFA='true';
process.env.CONTEXT='test';
globalThis.__NUTRETIUM_TEST_BLOBS__=new Map();
globalThis.__NUTRETIUM_TEST_BLOB_ETAGS__=new Map();
globalThis.__NUTRETIUM_RATE_LIMIT_FALLBACK__=new Map();
const usuarios=require('../netlify/lib/usuarios');
const passwords=require('../netlify/lib/passwords');
const totp=require('../netlify/lib/totp');
const staffLogin=require('../netlify/functions/staff-login');
const email='recovery-owner@nutretium.test',password='Recovery-Owner-2026!';
const base={id:'recovery-owner',name:'Owner',surname:'Recovery',email,phone:'',direccion:{},passwordHash:passwords.hashPassword(password),sessionVersion:0,createdAt:new Date().toISOString()};
const event=(body,ip='127.0.0.55')=>({httpMethod:'POST',headers:{'content-type':'application/json','x-nf-client-connection-ip':ip},body:JSON.stringify(body)});
const parse=r=>JSON.parse(r.body||'{}');
(async()=>{
 await usuarios.escribe(email,base);
 const first=await staffLogin.handler(event({email,password}));
 assert.strictEqual(first.statusCode,401,'El primer acceso privilegiado sin MFA debe iniciar enrolamiento, no bloquearse');
 const setup=parse(first);assert.strictEqual(setup.mfaSetupRequired,true);assert.strictEqual(setup.mfaRequired,true);assert(/^[A-Z2-7]+$/.test(setup.mfa.setupSecret));assert(setup.mfa.provisioningUri.startsWith('otpauth://totp/'));
 const stored=await usuarios.lee(email);assert.strictEqual(stored.mfaEnabled,true);assert(stored.mfaSecretEncrypted);assert.notStrictEqual(stored.mfaSecretEncrypted,setup.mfa.setupSecret);assert(stored.mfaEnrollmentPendingAt);
 const second=await staffLogin.handler(event({email,password}));assert.strictEqual(second.statusCode,401);assert.strictEqual(parse(second).mfa.setupSecret,setup.mfa.setupSecret,'Reintentar no debe regenerar la clave pendiente');
 const code=totp.code(setup.mfa.setupSecret);const confirmed=await staffLogin.handler(event({email,password,mfaCode:code}));assert.strictEqual(confirmed.statusCode,200,'Un código válido debe completar enrolamiento y permitir acceso');assert.strictEqual(parse(confirmed).user.mfa,true);
 const after=await usuarios.lee(email);assert(after.mfaConfiguredAt);assert(!after.mfaEnrollmentPendingAt);
 const wrongIp='127.0.0.77';for(let i=0;i<5;i++){const bad=await staffLogin.handler(event({email,password:'incorrecta-'+i},wrongIp));assert.strictEqual(bad.statusCode,401)}const validAfterBad=await staffLogin.handler(event({email,password,mfaCode:totp.code(setup.mfa.setupSecret)},wrongIp));assert.strictEqual(validAfterBad.statusCode,200,'Cinco errores de contraseña no deben encerrar inmediatamente una credencial válida');
 console.log('[test-staff-access-recovery] OK · enrolamiento MFA recuperable · clave estable · acceso válido tras errores previos');
})().catch(err=>{console.error(err);process.exit(1)});
