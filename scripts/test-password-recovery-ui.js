'use strict';
const fs=require('fs');
const path=require('path');
const assert=(cond,msg)=>{if(!cond)throw new Error(msg)};
const root=path.join(__dirname,'..');
const redirects=fs.readFileSync(path.join(root,'_redirects'),'utf8');
const html=fs.readFileSync(path.join(root,'cuenta.html'),'utf8');
const js=fs.readFileSync(path.join(root,'cuenta.js'),'utf8');
const security=fs.readFileSync(path.join(root,'netlify/functions/account-security.js'),'utf8');
assert(/^\/mi-nutretium\s+\/cuenta\.html\s+200$/m.test(redirects),'Falta la ruta /mi-nutretium -> /cuenta.html');
assert(/id="forgotPassword"/.test(html),'Falta el botón He olvidado mi contraseña');
assert(/id="resetRequestForm"/.test(html),'Falta el formulario para solicitar recuperación');
assert(/id="resetPasswordForm"/.test(html),'Falta el formulario para crear nueva contraseña');
assert(/action:'request-reset'/.test(js),'La interfaz no llama request-reset');
assert(/action:'reset-password'/.test(js),'La interfaz no llama reset-password');
assert(/new URLSearchParams\(location\.search\)\.get\('reset'\)/.test(js),'La interfaz no consume el token de recuperación de la URL');
assert(/RESET_TTL=30\*60\*1000/.test(security),'El backend ya no conserva TTL de 30 minutos');
assert(/used:false/.test(security)&&/finishClaim/.test(security),'El backend no mantiene semántica de token de un solo uso');
assert(/sessionVersion:Number\(current\.sessionVersion\|\|0\)\+1/.test(security),'El cambio de contraseña no revoca sesiones anteriores');
console.log('OK password recovery UI + route + backend contract');
